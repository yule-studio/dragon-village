     * 봉인지마다 나오는 드래곤이 다르고, 그 드래곤마다 앞라인에 세울 것이 다르다.
     * 편성을 틀리면 못 잡는다. 사용자가 알려준 공략을 그대로 적어둔다.
     *
     * `앞라인` 은 맨 앞에 세워야 하는 것이고, 탱커는 **체방 또는 체력** 타입이다.
